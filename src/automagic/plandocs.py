"""Committed plan documents: one markdown file per node plus a copy of the graph.

The files live in `docs/plan/` so the agreed intent travels with the repository.
Each node document records the node hash; `stale` reports documents whose hash no
longer matches the graph.
"""

from __future__ import annotations

import re
from pathlib import Path

from automagic.merkle import Graph
from automagic.render import hash_chain
from automagic.sizing import WorkItem

PLAN_DOCS = Path("docs") / "plan"
_MARK = re.compile(r"<!-- automagic:node (\S+) ([0-9a-f]{64}) -->")


def plan_dir(root: Path) -> Path:
    return root / PLAN_DOCS


def render_node_doc(
    graph: Graph, nid: str, item_id: str | None, history: list[dict], max_lines: int
) -> str:
    node = graph.nodes[nid]
    lines = [
        f"<!-- automagic:node {nid} {graph.node_hash(nid)} -->",
        f"# {node.title}",
        "",
        f"Node `{nid}`, hash `{graph.node_hash(nid)}`. Goal: {graph.goal}",
        f"Work item: `{item_id}`" if item_id else "Work item: not yet assigned",
        "",
        "## Agreed scope",
        "",
        node.content.strip() or "_No content recorded._",
        "",
        "## Boundaries",
        "",
        f"- Estimated change: about {node.est_lines} lines (budget {max_lines} per work item).",
    ]
    if node.files:
        lines.append("- Expected files: " + ", ".join(f"`{f}`" for f in node.files))
        lines.append(
            "- `automagic review` flags changes outside these files; guardrail, CI and "
            "config files need to be listed here to be changed."
        )
    else:
        lines.append("- No files declared, so the review scope check is skipped.")
    lines += ["", "## Depends on", ""]
    if node.depends_on:
        lines += [f"- [{graph.nodes[d].title}]({d}.md)" for d in sorted(node.depends_on)]
    else:
        lines.append("- Nothing.")
    dependents = sorted(n for n, other in graph.nodes.items() if nid in other.depends_on)
    if dependents:
        lines += ["", "## Required by", ""]
        lines += [f"- [{graph.nodes[d].title}]({d}.md)" for d in dependents]
    lines += ["", "## Hash chain", "", "```", *hash_chain(graph, nid), "```", ""]
    answered = [e for e in history if e.get("node") == nid and e.get("event") == "answered"]
    if answered:
        lines += ["## Decisions from the interview", ""]
        for e in answered:
            question, answer = e["question"].replace("\n", " "), e["answer"].replace("\n", " ")
            lines.append(f"- Q: {question}")
            lines.append(f"  A: {answer}")
        lines.append("")
    return "\n".join(lines)


def _index(graph: Graph, items: list[WorkItem]) -> str:
    owner = {n: i.id for i in items for n in i.node_ids}
    lines = [
        "# Plan documents",
        "",
        f"Goal: {graph.goal}",
        f"Root hash: `{graph.root_hash()}`",
        "",
        "Generated by `automagic plan` and `automagic show`; `graph.json` is the source graph.",
        "",
        "| Node | Work item | Depends on |",
        "|---|---|---|",
    ]
    for nid in graph.order():
        deps = ", ".join(sorted(graph.nodes[nid].depends_on)) or "-"
        lines.append(f"| [{graph.nodes[nid].title}]({nid}.md) | {owner.get(nid, '-')} | {deps} |")
    return "\n".join(lines) + "\n"


def write(
    root: Path, graph: Graph, items: list[WorkItem], history: list[dict], max_lines: int
) -> list[Path]:
    """Write node documents, the index and graph.json; drop documents of removed nodes."""
    out = plan_dir(root)
    out.mkdir(parents=True, exist_ok=True)
    owner = {n: i.id for i in items for n in i.node_ids}
    written: list[Path] = []
    for nid in graph.nodes:
        path = out / f"{nid}.md"
        path.write_text(render_node_doc(graph, nid, owner.get(nid), history, max_lines))
        written.append(path)
    for old in out.glob("*.md"):
        if old.stem not in graph.nodes and old.name != "_index.md":
            first = old.read_text().split("\n", 1)[0]
            if _MARK.match(first):
                old.unlink()
    (out / "_index.md").write_text(_index(graph, items))
    graph.save(out / "graph.json", include_checkpoint=False)
    return written


def stale(root: Path) -> list[str]:
    """Problems with committed plan documents compared to the committed graph."""
    out = plan_dir(root)
    graph_path = out / "graph.json"
    if not graph_path.exists():
        return []
    graph = Graph.load(graph_path, include_checkpoint=False)
    problems: list[str] = []
    for nid in graph.nodes:
        rel = (PLAN_DOCS / f"{nid}.md").as_posix()
        path = out / f"{nid}.md"
        if not path.exists():
            problems.append(f"{rel}: missing; run `automagic show`")
            continue
        match = _MARK.match(path.read_text().split("\n", 1)[0])
        if not match or match.group(2) != graph.node_hash(nid):
            problems.append(f"{rel}: out of date with graph.json; run `automagic show`")
    return problems
